#!/usr/bin/env python3
"""Build src/ui/src/lib/oui.ts: MAC prefix -> maker for common consumer and network brands.

Input: the IEEE MA-L registry, either IEEE's own oui.csv (https://standards-oui.ieee.org/oui/oui.csv)
or Wireshark's `manuf` (https://www.wireshark.org/download/automated/data/manuf, derived from it).
  python3 src/scripts/oui.py path/to/manuf-or-oui.csv YYYY-MM-DD > src/ui/src/lib/oui.ts
Only 24-bit (MA-L) blocks of the brands below are kept; everything else shows no maker.
"""
import csv
import re
import sys

BRANDS = {
    "Apple": r"Apple,? Inc", "Samsung": r"Samsung Electro", "Google": r"Google,? (Inc|LLC)", "Nest": r"Nest Labs",
    "Xiaomi": r"(Beijing )?Xiaomi", "Huawei": r"Huawei (Technologies|Device)", "Honor": r"Honor Device",
    "OnePlus": r"OnePlus", "OPPO": r"Guangdong Oppo", "vivo": r"vivo Mobile", "Motorola": r"Motorola Mobility",
    "Intel": r"Intel Corporat", "Realtek": r"Realtek", "TP-Link": r"TP-?LINK", "Ubiquiti": r"Ubiquiti",
    "MikroTik": r"(Routerboard|MikroTik)", "Amazon": r"Amazon Technologies", "Sonos": r"Sonos", "Espressif": r"Espressif",
    "Raspberry Pi": r"Raspberry Pi", "Microsoft": r"Microsoft", "Sony": r"Sony ", "LG": r"LG Electronics",
    "Nintendo": r"Nintendo", "HP": r"(Hewlett[ -]Packard|HP Inc)", "Dell": r"Dell ", "Lenovo": r"Lenovo",
    "ASUS": r"ASUSTek", "Netgear": r"NETGEAR", "Philips Hue": r"(Signify|Philips Lighting)", "Roku": r"Roku",
    "Synology": r"Synology", "QNAP": r"QNAP", "Brother": r"Brother Industries", "Canon": r"Canon ",
    "Epson": r"Seiko Epson", "Tuya": r"Tuya", "Shelly": r"(Allterco|Shelly)", "Bose": r"Bose ", "Garmin": r"Garmin",
    "Fitbit": r"Fitbit", "AVM": r"AVM (Audiovisuelles|GmbH)", "Cisco": r"Cisco Systems", "Nvidia": r"NVIDIA",
    "Valve": r"Valve ", "Panasonic": r"Panasonic", "Hisense": r"Hisense", "TCL": r"TCL ", "Vizio": r"VIZIO",
    "Belkin": r"Belkin", "D-Link": r"D-Link", "Zyxel": r"Zyxel", "IKEA": r"IKEA", "Ring": r"Ring LLC",
    "ecobee": r"ecobee", "Dyson": r"Dyson", "Withings": r"Withings", "Ezviz/Hikvision": r"Hangzhou Hikvision",
}
pats = {b: re.compile(p, re.I) for b, p in BRANDS.items()}

def rows(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        if path.endswith(".csv"):  # IEEE: Registry,Assignment,Organization Name,...
            for r in csv.reader(f):
                if len(r) > 2 and r[0] == "MA-L":
                    yield r[1].upper(), r[2]
        else:  # manuf: "00:00:0C<tab>Short<tab>Long name"; /28 and /36 blocks carry a mask and are skipped
            for line in f:
                p = line.rstrip("\n").split("\t")
                if line.startswith("#") or len(p) < 2 or "/" in p[0] or len(p[0].strip()) != 8:
                    continue
                yield p[0].strip().replace(":", "").upper(), (p[2] if len(p) > 2 else p[1]).strip()

out = {}
for prefix, org in rows(sys.argv[1]):
    for b, pat in pats.items():
        if pat.match(org):
            out.setdefault(b, []).append(prefix)
            break

print(f"// Generated by src/scripts/oui.py from the IEEE MA-L registry ({sys.argv[2]}); do not edit by hand.")
print("// Brand -> 24-bit MAC prefixes (hex, no separators), space-separated.")
print("export const OUI: Record<string, string> = {")
for b in sorted(out):
    print(f"  {b!r}: '{' '.join(sorted(out[b]))}',".replace('"', "'"))
print("}")
