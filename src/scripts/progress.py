#!/usr/bin/env python3
"""Recount status emoji in docs/FEATURES.md tables and rewrite the progress line.

Rows that carry the 🔌 flag need a test on real hardware (a MikroTik router, a Wi-Fi AP, a physical
port, a real ISP line or a real outside service) before they can be ✅. The text after 🔌 in the
feature cell says what to check. They are collected into docs/HARDWARE_TESTS.md.
"""
import re, pathlib, sys

STATES = ["✅", "🟨", "🎨", "⬜", "➖"]
HW = "🔌"
root = pathlib.Path(__file__).resolve().parents[2]
p = root / "docs" / "FEATURES.md"
text = p.read_text(encoding="utf-8")

counts = dict.fromkeys(STATES, 0)
hw = []  # (section, feature, check, status)
section = ""
for line in text.splitlines():
    if line.startswith("## "):
        section = line[3:].strip()
    if line.startswith("|"):
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        last = cells[-1]  # status is always the last column
        if last in counts:
            counts[last] += 1
            feature = next((c for c in cells if HW in c), None)
            if feature is not None and last != "✅":
                name, _, check = feature.partition(HW)
                name, check = name.strip(), check.strip()
                if name.endswith("("):  # written as "Feature (🔌 check)"
                    name, check = name[:-1].strip(), check.removesuffix(")").strip()
                hw.append((section, name, check, last))

total = sum(counts.values())
done = counts["✅"] / max(total - counts["➖"], 1) * 100
summary = " · ".join(f"{counts[s]} {s}" for s in STATES)
line = f"**Progress:** {summary} ({total} items, {done:.0f}% done) · {len(hw)} {HW} waiting for a hardware test ([list](HARDWARE_TESTS.md))"
block = f"<!-- progress:start -->\n{line}\n<!-- progress:end -->"
text = re.sub(r"<!-- progress:start -->.*?<!-- progress:end -->", block, text, flags=re.S)
p.write_bytes(text.encode("utf-8"))  # bytes: Windows text mode would turn LF into CRLF

# docs/HARDWARE_TESTS.md: the generated checklist
out = [
    "# Hardware test checklist",
    "",
    "Generated by `src/scripts/progress.py` from the 🔌 flags in [FEATURES.md](FEATURES.md); edit the flags there, not this file.",
    "Each item is built and unit-tested, but needs a check on real equipment before it can be ✅.",
    "Read-only checks first; test anything that writes on a spare router or CHR, never on a live network without a Safe apply window.",
    "",
]
cur = None
for sec, name, check, status in hw:
    if sec != cur:
        out += ["", f"## {sec}", ""]
        cur = sec
    out.append(f"- [ ] **{name}** {status}: {check}")
(root / "docs" / "HARDWARE_TESTS.md").write_bytes(("\n".join(out).replace("\n\n\n", "\n\n") + "\n").encode("utf-8"))

sys.stdout.reconfigure(encoding="utf-8")  # Windows consoles default to cp1252
print(line)
